const data = await (await fetch(`${BASE}/data/simple-icons.json`)).json();
const list = Array.isArray(data) ? data : data.icons;

/** Simple Icons slug rules: lowercase, "+" → plus, "." → dot, accents and symbols removed. */
function slugOf(icon) {
    if (icon.slug) {
        return icon.slug;
    }
    return icon.title
        .toLowerCase()
        .replace(/\+/g, 'plus')
        .replace(/^\./, 'dot-')
        .replace(/\.(?=.)/g, 'dot')
        .replace(/&/g, 'and')
        .normalize('NFD')
        .replace(/[^a-z0-9]/g, '');
}

const colors = new Map(list.map(i => [slugOf(i), i.hex]));
const logos = {};
const missing = [];
for (const slug of slugs) {
    const res = await fetch(`${BASE}/icons/${slug}.svg`);
    if (!res.ok) {
        missing.push(slug);
        continue;
    }
    const svg = await res.text();
    const path = svg.match(/<path d="([^"]+)"/)?.[1];
    if (!path) {
        missing.push(slug);
        continue;
    }
    logos[slug] = { hex: colors.get(slug) ?? '888888', path };
}

